/**
 * Downloads the photographs listed in `src/content/photos.js` and writes optimised, responsive WebP files.
 *
 *   public/photos/<name>-<width>.webp   one file per width (never upscaled)
 *   src/content/photoMeta.js            intrinsic ratio + tiny blurred placeholder per photo
 *
 * Originals are cached in `scripts/.photo-cache/` (git-ignored), so re-running only re-encodes.
 * Usage: npm run photos [-- --force]
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { PHOTO_WIDTHS, PHOTOS } from '../src/content/photos.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const cacheDir = path.join(root, 'scripts/.photo-cache')
const outDir = path.join(root, 'public/photos')
const metaFile = path.join(root, 'src/content/photoMeta.js')
const force = process.argv.includes('--force')
const SOURCE_WIDTH = 2800

fs.mkdirSync(cacheDir, { recursive: true })
fs.mkdirSync(outDir, { recursive: true })

const download = async (source) => {
  const file = path.join(cacheDir, `${source}.jpg`)
  if (fs.existsSync(file) && !force) return file
  const response = await fetch(`https://images.unsplash.com/${source}?w=${SOURCE_WIDTH}&q=90&fm=jpg`)
  if (!response.ok) throw new Error(`${source}: HTTP ${response.status}`)
  fs.writeFileSync(file, Buffer.from(await response.arrayBuffer()))
  return file
}

const meta = {}
for (const [name, photo] of Object.entries(PHOTOS)) {
  const original = await download(photo.source)
  const image = sharp(original).rotate()
  const { width, height } = await image.metadata()
  const widths = (photo.widths || PHOTO_WIDTHS).filter((w) => w <= width)
  for (const w of widths) {
    const target = path.join(outDir, `${name}-${w}.webp`)
    if (fs.existsSync(target) && !force) continue
    await image.clone().resize({ width: w }).webp({ quality: w > 1400 ? 70 : 74, effort: 6, smartSubsample: true }).toFile(target)
  }
  const placeholder = await image.clone().resize({ width: 24 }).blur(1.2).webp({ quality: 40 }).toBuffer()
  meta[name] = { ratio: +(width / height).toFixed(4), widths, blur: `data:image/webp;base64,${placeholder.toString('base64')}` }
  console.log(`✓ ${name.padEnd(20)} ${widths.join(', ')}`)
}

fs.writeFileSync(
  metaFile,
  `// Generated by scripts/fetch-photos.mjs — do not edit by hand.\nexport const PHOTO_META = ${JSON.stringify(meta, null, 2)}\n`,
)
console.log(`Photo metadata written to ${path.relative(root, metaFile)}`)
